1. USERS, CATEGORIES, PRODUCTS,
   ORDERS, ORDER_ITEMS, CART_ITEMS 생성

2. 회원 3명 등록
3. 카테고리 3개 등록
4. 상품 5개 등록

※ 위 작업은 실행 완료되어 재실행 방지를 위해 주석 처리
*/

CREATE TABLE USERS (
    USER_NUMBER NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_EMAIL VARCHAR2(254) UNIQUE NOT NULL,
    USER_NAME VARCHAR2(10) NOT NULL,
    USER_ID VARCHAR2(15) UNIQUE NOT NULL,
    USER_PASSWORD VARCHAR2(255) NOT NULL,
    USER_CREATED_AT DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE CATEGORIES (
    CATEGORIES_NUMBER NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CATEGORIES_NAME VARCHAR2(50) UNIQUE NOT NULL
);

CREATE TABLE PRODUCTS (
    PRODUCT_NUMBER NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(20) NOT NULL,
    CATEGORIES_NUMBER NUMBER NOT NULL,
    PRODUCT_PRICE NUMBER(10) CHECK(PRODUCT_PRICE >= 0) NOT NULL,
    PRODUCT_STOCK NUMBER(5) DEFAULT 0 CHECK(PRODUCT_STOCK >= 0) NOT NULL,
    PRODUCT_DESC VARCHAR2(100),
    PRODUCT_DATE DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_PRODUCTS_CATEGORIES
    FOREIGN KEY (CATEGORIES_NUMBER)
    REFERENCES CATEGORIES (CATEGORIES_NUMBER)
);

CREATE TABLE ORDERS (
    ORDERS_NUMBER NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_NUMBER NUMBER NOT NULL,
    ORDERS_DATE DATE DEFAULT SYSDATE NOT NULL,
    ORDERS_STATE VARCHAR2(20) DEFAULT 'PENDING' CHECK(ORDERS_STATE IN('PENDING','PAID','SHIPPED','CANCELLED')) NOT NULL,
    ORDERS_TOTALPRICE NUMBER(10) CHECK(ORDERS_TOTALPRICE >= 0) NOT NULL,
    CONSTRAINT FK_ORERS_USER
    FOREIGN KEY (USER_NUMBER)
    REFERENCES USERS (USER_NUMBER)
);

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEMS_NUMBER NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDERS_NUMBER NUMBER NOT NULL,
    PRODUCT_NUMBER NUMBER NOT NULL,
    ORDER_ITEMS_QUANTITY NUMBER(5) NOT NULL CHECK(ORDER_ITEMS_QUANTITY >= 1),
    ORDER_ITEMS_UNITPRICE NUMBER(10) CHECK(ORDER_ITEMS_UNITPRICE >= 0) NOT NULL,

    CONSTRAINT FK_ORDER_ITEMS_ORDERNO
    FOREIGN KEY (ORDERS_NUMBER)
    REFERENCES ORDERS (ORDERS_NUMBER),
    
    CONSTRAINT FK_ORDER_ITEMS_PRODUCTNO
    FOREIGN KEY (PRODUCT_NUMBER)
    REFERENCES PRODUCTS (PRODUCT_NUMBER),
    
    UNIQUE (ORDERS_NUMBER, PRODUCT_NUMBER)
);

CREATE TABLE CART_ITEMS (
    CART_ITEM_NUMBER NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_NUMBER NUMBER NOT NULL,
    PRODUCT_NUMBER NUMBER NOT NULL,
    CART_ITEM_STOCK NUMBER(5) DEFAULT 1 CHECK(CART_ITEM_STOCK >= 1) NOT NULL,
    CART_ITEM_DATE DATE DEFAULT SYSDATE NOT NULL,
    
    CONSTRAINT CART_ITEMS_USERNO
    FOREIGN KEY (USER_NUMBER)
    REFERENCES USERS (USER_NUMBER),
    
    CONSTRAINT CART_ITEMS_PRODUCTNO
    FOREIGN KEY (PRODUCT_NUMBER)
    REFERENCES PRODUCTS (PRODUCT_NUMBER),
       
    UNIQUE (USER_NUMBER, PRODUCT_NUMBER) 
);